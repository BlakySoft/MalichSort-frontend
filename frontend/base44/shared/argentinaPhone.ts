export function isArgentinaPhone(phone: string): boolean {
  const match = /^(\+\d{1,4}) (\d{2,5}) (\d{6,8})$/.exec(String(phone || ''));
  return Boolean(match && match[1] === ARGENTINA_COUNTRY_CODE && ARGENTINA_AREA_CODES.has(match[2]));
}